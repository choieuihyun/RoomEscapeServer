-- 동호회 일정 · 테마 구간 · 참여자 (아키텍처 D30 · D31). 계약은 Floduler `작업명세서.md` §4.7.
--
-- 시각은 전부 **자정부터의 분(INTEGER)** 이다. 0~2879 — 다음날 23:59 까지.
-- Postgres TIME 은 24:00 을 넘는 값을 못 담는데, 자정 넘는 회차(다음날 00:30 = 1470)가 실제로 있다.

CREATE TABLE club_event (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 0~60자(코드 포인트). 비어 있으면 화면이 구간으로 제목을 만들어 보여 준다 — 저장은 빈 채로
    title       VARCHAR(60)  NOT NULL,
    -- 한국 날짜
    event_date  DATE         NOT NULL,
    -- 둘 다 비면 "하루 종일"(또는 구간 시각을 쓴다)
    start_min   INTEGER,
    end_min     INTEGER,
    location    VARCHAR(60),
    -- 비면 제한 없음
    capacity    INTEGER      CHECK (capacity IS NULL OR capacity BETWEEN 2 AND 8),
    -- 예약 완료 여부. "협의 중 / 예약 전 / 예약 완료" 는 저장하지 않고 화면이 구간 유무와 이 값에서 만든다 (D30)
    booked      BOOLEAN      NOT NULL,
    memo        VARCHAR(500),
    created_by  VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    -- **내용이 바뀐 때만** 바뀐다. 참여로는 안 바뀐다 (D31)
    updated_at  TIMESTAMPTZ  NOT NULL,
    -- 낙관적 잠금 (@Version). 화면이 받아 둔 값과 다르면 수정을 덮어쓰지 않는다 (D31)
    version     BIGINT       NOT NULL,
    -- 지우지 않고 표시만 한다. 실수 복구, 그리고 뒤 단계의 알림·기록이 사라진 일정을 가리키지 않게
    deleted_at  TIMESTAMPTZ,
    deleted_by  VARCHAR(255),
    CONSTRAINT ck_club_event_time CHECK (
        (start_min IS NULL AND end_min IS NULL)
        OR (start_min IS NOT NULL AND end_min IS NOT NULL AND start_min >= 0 AND start_min < end_min AND end_min <= 2879)
    )
);

-- 목록은 늘 "이 날짜 범위의 지워지지 않은 일정" 이다
CREATE INDEX idx_club_event_date ON club_event (event_date) WHERE deleted_at IS NULL;

-- 테마 구간. JSON 열이 아니라 표인 이유는 D30 — 뒤 단계가 테마 키로 찾는다.
-- 수정은 목록 통째로 바꾼다. ⚠️ Hibernate 는 INSERT 를 DELETE 보다 먼저 내보내서, 아래 UNIQUE 와 겹치면 터진다 —
-- 서비스가 지우기를 별도 쿼리로 먼저 내보낸다 (D30 "순서 함정")
CREATE TABLE club_event_segment (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL,
    -- 보낸 순서. 0 부터
    position    INTEGER      NOT NULL,
    theme_name  VARCHAR(40)  NOT NULL,
    branch_name VARCHAR(40),
    -- 서버 테마 키(`play33-konkuk:18`). **형식만 본다** — 테마가 사라져도 일정은 그대로여야 해서 theme 표와 묶지 않는다
    theme_key   VARCHAR(80),
    start_min   INTEGER      NOT NULL,
    end_min     INTEGER,
    CONSTRAINT fk_segment_event FOREIGN KEY (event_id) REFERENCES club_event (id),
    CONSTRAINT uk_segment_event_position UNIQUE (event_id, position),
    CONSTRAINT ck_segment_time CHECK (
        start_min >= 0 AND start_min <= 2879 AND (end_min IS NULL OR (end_min > start_min AND end_min <= 2879))
    )
);

-- 참여자. **일정 행 밖에** 둔다 — 참여가 일정의 version 을 올리면 편집 중인 사람이 충돌을 받는다 (D31)
CREATE TABLE club_event_participant (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL,
    -- Firebase uid. 내보낸 멤버여도 행은 남는다 (닉네임도 그대로 보인다)
    user_id     VARCHAR(255) NOT NULL,
    -- 대신 넣었을 때 넣은 사람. 스스로 참여했으면 비어 있다
    added_by    VARCHAR(255),
    joined_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_participant_event FOREIGN KEY (event_id) REFERENCES club_event (id),
    -- 버튼을 두 번 눌러도, 대신 넣기와 겹쳐도 한 사람은 한 자리
    CONSTRAINT uk_participant_event_user UNIQUE (event_id, user_id)
);
