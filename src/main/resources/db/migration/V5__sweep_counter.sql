-- 수집 바퀴 번호. 이 한 줄이 "지금 몇 번째 바퀴인가" 를 들고 있다.
--
-- ## 왜 테이블까지 만들었나 (2026-09-01)
--
-- 전에는 번호를 시계에서 뽑았다 — `now / collector.interval-ms`.
-- 카운터를 메모리에 두면 서버를 재시작할 때마다 0 으로 돌아가서, 개발 중에 자주 껐다 켜면
-- 같은 평일만 계속 보고 나머지 날짜가 굶기 때문이었다.
--
-- **그런데 시계에서 뽑는 것이 더 크게 굶었다.** 나누는 값이 300초(설정값)인데
-- 한 바퀴는 실제로 470초쯤 걸린다 (fixedDelay 라 "끝난 뒤 5분" + 수집 시간).
-- 그래서 번호가 한 바퀴에 1~2 씩 들쭉날쭉 뛰고, `sweep % 2`(금요일)도
-- `sweep % 4`(평일 순환)도 균등하지 않게 된다.
--
--   실측 2026-09-01 (8바퀴 · 53분)
--     금요일이 나온 바퀴   ✗ ✗ ● ● ✗ ✗ ● ●   둘씩 몰린다
--     먼 창 8일 중         09-08 · 09-13 은 53분 동안 한 번도 안 봤다
--
-- 나눗수를 470초로 고치는 방법도 있었지만 **버리기로 했다** — 매장이 늘어 수집이 느려지면
-- 또 틀어진다. 설정값을 실제값이라고 믿는 것이 애초의 실수였고, 그 실수를 반복하는 셈이다.
--
-- 쓰기는 **바퀴당 UPDATE 한 번**(하루 180번쯤)이고 행이 늘지 않는다. 디스크에 영향 없다.

CREATE TABLE sweep_counter (
    -- 항상 1. 한 줄만 존재해야 하므로 CHECK 로 못 박는다 —
    -- 두 줄이 되면 "어느 쪽이 진짜 번호냐" 가 조용히 갈린다
    id       SMALLINT PRIMARY KEY,
    -- `value` 로 두면 H2(테스트용)에서 예약어라 쿼리가 통째로 깨진다.
    -- Postgres 는 받아 주므로 **운영에서는 멀쩡한데 테스트만 안 도는** 모양이 된다
    sweep_no BIGINT   NOT NULL,
    CONSTRAINT ck_sweep_counter_single_row CHECK (id = 1)
);

INSERT INTO sweep_counter (id, sweep_no) VALUES (1, 0);
