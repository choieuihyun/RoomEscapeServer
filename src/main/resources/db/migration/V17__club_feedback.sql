-- 글 · 공감 · 댓글 표 셋. 글을 지우면 공감·댓글도 같이 사라진다 — 서비스가 먼저 지우고, 외래 키의 ON DELETE CASCADE 는
-- 손으로 지울 때(운영 DB 정리)를 위한 두 번째 줄이다.
-- 글자 수는 서비스가 코드 포인트로 센다 (글 1~1000 · 댓글 1~300 · VARCHAR 와 같은 셈)

CREATE TABLE club_feedback (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    VARCHAR(255)  NOT NULL,
    text       VARCHAR(1000) NOT NULL,
    status     VARCHAR(8)    NOT NULL CHECK (status IN ('OPEN', 'REVIEW', 'DONE', 'HOLD')),
    created_at TIMESTAMPTZ   NOT NULL,
    -- 글을 고친 때. 상태·공감·댓글로는 안 바뀐다 (처음엔 created_at 과 같다)
    updated_at TIMESTAMPTZ   NOT NULL,
    -- 마지막으로 상태를 바꾼 때·사람. OPEN 이면 둘 다 null
    status_at  TIMESTAMPTZ,
    status_by  VARCHAR(255)
);

-- 공감은 사람마다 글마다 하나 — 같은 순간 두 번 눌러도 UNIQUE 가 막는다(서비스는 글 행을 잠가 차례로 받는다)
CREATE TABLE club_feedback_like (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT       NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_feedback_like_feedback FOREIGN KEY (feedback_id) REFERENCES club_feedback (id) ON DELETE CASCADE,
    CONSTRAINT uq_feedback_like UNIQUE (feedback_id, user_id)
);

CREATE TABLE club_feedback_comment (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT       NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    text        VARCHAR(300) NOT NULL,
    -- 쓸 때 운영진이었나. 저장 값이다 — 나중에 역할이 바뀌어도 그 댓글의 "운영진" 표시는 그대로
    admin       BOOLEAN      NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_feedback_comment_feedback FOREIGN KEY (feedback_id) REFERENCES club_feedback (id) ON DELETE CASCADE
);
CREATE INDEX ix_feedback_comment_feedback ON club_feedback_comment (feedback_id);
