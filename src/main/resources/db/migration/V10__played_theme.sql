-- 해 본 테마 (아키텍처 D33). 계약은 Floduler `작업명세서.md` §4.9.

CREATE TABLE played_theme (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Firebase uid
    user_id     VARCHAR(255) NOT NULL,
    -- 서버 테마 키(`play33-konkuk:18`). 없으면 이름으로만 판정한다
    theme_key   VARCHAR(80),
    theme_name  VARCHAR(40)  NOT NULL,
    branch_name VARCHAR(40),
    -- 정리한 이름 (NFKC → 소문자 → 글자·숫자만). **Kotlin 이 만들어 넣는다** — SQL 함수는 Postgres·H2 가 다르게 정리한다.
    -- NFKC 는 글자를 늘릴 수 있어(㎏ → kg) 원래 이름보다 넉넉히 잡는다
    name_key    VARCHAR(200) NOT NULL,
    played_on   DATE,
    source      VARCHAR(16)  NOT NULL CHECK (source IN ('MANUAL', 'PLAN', 'EVENT')),
    -- 자동 기록이면 그 일정
    event_id    BIGINT,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_played_event FOREIGN KEY (event_id) REFERENCES club_event (id)
);
-- "같은 테마" 는 UNIQUE 로 못 건다 — 규칙이 이행적이지 않다 (D33). 늘 사람 단위로 읽는다
CREATE INDEX idx_played_user ON played_theme (user_id);

-- 자동 기록을 한 일정. 벌크 UPDATE 로만 단다 — 엔티티로 고치면 version 이 올라 편집 중인 사람이 충돌을 받는다 (D33)
ALTER TABLE club_event ADD COLUMN played_recorded_at TIMESTAMPTZ;
