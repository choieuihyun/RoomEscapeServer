-- 20:00~21:55 사이 5분마다 "내일 일정 × 참여자 중 아직 SENT 가 없는 사람" 에게 보낸다. 이 표가 중복을 막는다.
-- SENT 만 "보냈다" 로 센다 — 실패를 보냄으로 세면 그 사람은 조용히 못 받는다 (빈자리 알림 notification_log 와 같은 규칙).
-- 기기가 없는 사람은 기록하지 않는다 — 시도가 아니라 설정 상태다 (D17)
CREATE TABLE club_event_reminder (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    -- 그 일정의 날짜. 날짜가 바뀌면 새 날짜로 다시 보내고, 시간만 바뀌면 다시 안 보낸다 — 계약이 이 키 하나로 나온다
    remind_for  DATE         NOT NULL,
    outcome     VARCHAR(16)  NOT NULL CHECK (outcome IN ('SENT', 'FAILED')),
    sent_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_reminder_event FOREIGN KEY (event_id) REFERENCES club_event (id)
);
-- 만에 하나 두 번 돌아도 두 번째 SENT 는 막힌다. FAILED 는 여러 번 남아도 된다(다시 시도한 흔적)
CREATE UNIQUE INDEX uk_reminder_sent ON club_event_reminder (event_id, user_id, remind_for) WHERE outcome = 'SENT';
