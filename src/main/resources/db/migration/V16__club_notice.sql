-- **한 번에 하나만** 걸린다. 그런데 행 하나를 고쳐 쓰지 않고, 쓸 때마다 지우고 새로 넣는다 —
-- 앱이 "이 공지를 닫았나" 를 id 로 기억하므로 고친 공지는 **새 id** 여야 다시 보인다. 늘어나는 id 는 IDENTITY 가 준다.
-- 운영진 둘이 같은 순간 쓰면 잠깐 두 행이 될 수 있다 — 읽을 때 id 가 가장 큰 것 하나만 보고, 다음 쓰기가 지운다
-- 글은 서비스가 코드 포인트로 1~500자를 센다 (VARCHAR 와 같은 셈)
CREATE TABLE club_notice (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text       VARCHAR(500) NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    updated_by VARCHAR(255) NOT NULL
);
