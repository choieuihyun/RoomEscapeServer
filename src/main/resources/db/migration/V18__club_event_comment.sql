-- 의견 댓글(V17)과 같은 모양 + 일정. 일정 지우기는 표시만(deleted_at)이라 CASCADE 가 돌 일은 없고 —
-- 서비스가 일정을 지울 때 댓글을 먼저 지운다. CASCADE 는 손으로 일정 행을 지울 때(운영 DB 정리)를 위한 두 번째 줄이다.
-- 글자 수는 서비스가 코드 포인트로 센다 (1~300 · 10줄 · VARCHAR 와 같은 셈)

CREATE TABLE club_event_comment (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT       NOT NULL,
    user_id    VARCHAR(255) NOT NULL,
    text       VARCHAR(300) NOT NULL,
    -- 쓸 때 운영진이었나. 저장 값이다 — 나중에 역할이 바뀌어도 그 댓글의 "운영진" 표시는 그대로
    admin      BOOLEAN      NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_event_comment_event FOREIGN KEY (event_id) REFERENCES club_event (id) ON DELETE CASCADE
);
CREATE INDEX ix_event_comment_event ON club_event_comment (event_id);
