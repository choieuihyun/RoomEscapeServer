-- 하고 싶은 테마 (아키텍처 D36) · 정산 · 송금 정보 (D37). 계약은 Floduler `작업명세서.md` §4.12 · §4.13.
-- uid 는 played_theme 처럼 그냥 문자열이다 — 멤버 행과 FK 로 잇지 않는다

-- 하고 싶은 테마 한 줄. "같은 테마" 는 UNIQUE 로 못 건다 — 규칙이 이행적이지 않다 (D33 · D36)
CREATE TABLE club_wish (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     VARCHAR(255) NOT NULL,
    theme_key   VARCHAR(80),
    theme_name  VARCHAR(40)  NOT NULL,
    branch_name VARCHAR(40),
    -- 정리한 이름. 해 본 테마와 같다 — Kotlin 이 만들어 넣는다
    name_key    VARCHAR(200) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_wish_user ON club_wish (user_id);

-- 정산 머리. **한 번 생기면 안 지운다** — 항목을 다 비워도 version 이 계속 올라야 낡은 화면이 덮어쓰지 못한다 (D37)
CREATE TABLE settlement (
    event_id   BIGINT       PRIMARY KEY,
    version    BIGINT       NOT NULL CHECK (version >= 1),
    updated_at TIMESTAMPTZ  NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    CONSTRAINT fk_settlement_event FOREIGN KEY (event_id) REFERENCES club_event (id)
);

-- 항목 하나. 보낸 순서(position)대로 읽는다. 저장할 때마다 통째로 바꾼다
CREATE TABLE settlement_item (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT       NOT NULL,
    position  INTEGER      NOT NULL CHECK (position BETWEEN 0 AND 29),
    -- 서비스가 코드 포인트로 1~20자를 센다
    label     VARCHAR(20)  NOT NULL,
    -- 원. 계약이 1 ~ 1,000만
    amount    INTEGER      NOT NULL CHECK (amount BETWEEN 1 AND 10000000),
    payer_uid VARCHAR(255) NOT NULL,
    CONSTRAINT fk_settlement_item_event FOREIGN KEY (event_id) REFERENCES club_event (id),
    CONSTRAINT uq_settlement_item_position UNIQUE (event_id, position)
);

-- 같이 낸 사람의 몫. 몫의 합 = 항목 금액은 서비스가 본다
CREATE TABLE settlement_share (
    id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT       NOT NULL,
    user_id VARCHAR(255) NOT NULL,
    amount  INTEGER      NOT NULL CHECK (amount >= 0),
    CONSTRAINT fk_settlement_share_item FOREIGN KEY (item_id) REFERENCES settlement_item (id) ON DELETE CASCADE,
    CONSTRAINT uq_settlement_share UNIQUE (item_id, user_id)
);

-- "보냈어요" — 행이 있으면 보낸 것이다. 그때 금액을 같이 둔다: 저장으로 그 쌍의 금액이 바뀌면 체크를 푼다 (D37)
CREATE TABLE settlement_transfer (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT       NOT NULL,
    from_uid VARCHAR(255) NOT NULL,
    to_uid   VARCHAR(255) NOT NULL,
    amount   BIGINT       NOT NULL CHECK (amount >= 1),
    paid_at  TIMESTAMPTZ  NOT NULL,
    paid_by  VARCHAR(255) NOT NULL,
    CONSTRAINT fk_settlement_transfer_event FOREIGN KEY (event_id) REFERENCES club_event (id),
    CONSTRAINT uq_settlement_transfer UNIQUE (event_id, from_uid, to_uid)
);

