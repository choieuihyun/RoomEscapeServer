-- 동호회 시간 협의 (아키텍처 D32). 계약은 Floduler `작업명세서.md` §4.8.

-- 날짜 미정 = NULL. "그러면 후보가 1개 이상" 은 다른 표라 CHECK 로 못 걸어서 서비스가 본다.
-- 첫 후보를 넣어 두지 않는 이유: 뒤 단계(전날 알림 · 해 본 테마 자동 기록)가 event_date 로 고르므로
-- 거짓 날짜가 있으면 안 정한 날짜로 알림이 나간다. NULL 이면 그 작업들이 저절로 건너뛴다
ALTER TABLE club_event ALTER COLUMN event_date DROP NOT NULL;

-- 목록 범위 조회가 "미정이고 후보가 범위 안" 도 찾는다 — 그 조회용 인덱스는 아래 cand_date
CREATE TABLE club_event_candidate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT NOT NULL,
    cand_date  DATE   NOT NULL,
    CONSTRAINT fk_candidate_event FOREIGN KEY (event_id) REFERENCES club_event (id),
    CONSTRAINT uk_candidate_event_date UNIQUE (event_id, cand_date)
);
CREATE INDEX idx_candidate_date ON club_event_candidate (cand_date);

-- 응답은 후보 행에 매단다 — 후보를 빼면 그 날짜 응답도 같이 지워야 해서.
-- ON DELETE CASCADE 는 **일부러 안 건다.** 테스트의 H2 는 엔티티로 표를 만들어 CASCADE 가 없다 —
-- 서비스가 응답부터 지우고 후보를 지운다 (D32)
CREATE TABLE club_event_availability (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT       NOT NULL,
    -- Firebase uid. 참여를 취소하면 서비스가 지운다
    user_id      VARCHAR(255) NOT NULL,
    available    BOOLEAN      NOT NULL,
    -- 둘 다 비면 "종일 됨"(available 일 때) 또는 "안 됨". 날짜마다 시간대는 하나
    start_min    INTEGER,
    end_min      INTEGER,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_availability_candidate FOREIGN KEY (candidate_id) REFERENCES club_event_candidate (id),
    -- 같은 날짜에 다시 고르면 덮어쓴다. 두 번 눌러도 한 줄
    CONSTRAINT uk_availability_candidate_user UNIQUE (candidate_id, user_id),
    CONSTRAINT ck_availability_time CHECK (
        (start_min IS NULL AND end_min IS NULL)
        OR (available AND start_min IS NOT NULL AND end_min IS NOT NULL
            AND start_min >= 0 AND start_min < end_min AND end_min <= 2879)
    )
);
