-- 동호회 멤버십(아키텍처 D28) — 누가 멤버이고, 어느 카카오 계정이 어느 uid 인지.
--
-- **신원은 여전히 Firebase 다.** 여기 있는 것은 "이 uid 가 동호회에서 어떤 자격인가" 뿐이고,
-- 비밀번호 같은 로그인 수단은 없다.

CREATE TABLE club_member (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Firebase uid (토큰의 `sub`). watch.user_id · device_token.user_id 와 같은 값이다
    user_id     VARCHAR(255) NOT NULL,
    -- 오픈채팅 닉네임. 관리자가 이걸 보고 승인한다. 앞뒤 공백을 지운 뒤 1~20자 (서비스가 자른다)
    nickname    VARCHAR(20)  NOT NULL,
    -- CHECK 를 거는 이유: 오타 난 값이 들어가면 enum 으로 읽는 순간 그 행을 건드리는 화면이 전부 터진다.
    -- 쓰는 순간 막아야 원인이 그 자리에 남는다
    role        VARCHAR(16)  NOT NULL CHECK (role IN ('ADMIN', 'MEMBER')),
    -- 행이 없는 것도 상태다 — API 는 그걸 NONE 으로 보여 준다 (가입 신청 전).
    -- REMOVED 는 지우지 않고 남긴다. 지우면 내보낸 사람이 다시 신청할 수 있게 된다
    status      VARCHAR(16)  NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REMOVED')),
    created_at  TIMESTAMPTZ  NOT NULL,
    -- 마지막으로 승인·거절·내보내기를 한 때와 한 사람. 가입 신청만 한 동안은 비어 있다
    decided_at  TIMESTAMPTZ,
    decided_by  VARCHAR(255),
    -- 가입 버튼을 두 번 눌러도 사람은 하나다
    CONSTRAINT uk_club_member_user UNIQUE (user_id)
);

-- 관리 화면은 상태별 목록으로 시작한다 ("승인 대기")
CREATE INDEX idx_club_member_status ON club_member (status);

-- "이 카카오 계정으로 들어오면 이 uid 다".
--
-- 카카오는 Firebase 가 직접 모르는 로그인이라, 서버가 카카오 회원번호를 확인하고 커스텀 토큰을 만든다.
-- 그때 **어느 uid 로** 만들지를 여기서 찾는다. 기존 아이디 계정에 카카오를 "연결" 하면
-- 이 표에 그 uid 가 들어가고, 다음부터 카카오로 들어와도 같은 uid 가 된다 —
-- uid 가 개인 일정·빈자리 알림·기기 토큰의 열쇠라서, 바뀌면 그게 다 끊긴다.
CREATE TABLE kakao_link (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 카카오 회원번호. 앱마다 고정이고 사람이 바꿀 수 없다 (닉네임·이메일은 바뀐다)
    kakao_id    BIGINT       NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    -- 카카오 하나는 계정 하나에만
    CONSTRAINT uk_kakao_link_kakao UNIQUE (kakao_id),
    -- 계정 하나에는 카카오 하나만. 서비스도 검사하지만, "연결" 을 두 탭에서 동시에 누르면
    -- 둘 다 "아직 없다" 를 보고 통과한다. 마지막 판정은 DB 가 한다
    CONSTRAINT uk_kakao_link_user UNIQUE (user_id)
);
