package com.my_dream.server.domain

import java.time.LocalDateTime

/**
 * **"지난 자리" 의 뜻을 정하는 단 한 곳.**
 *
 * 이 말이 코드 네 군데에서 필요하다.
 *
 * ```
 * ① 감시 목록          지나간 회차를 지켜보고 있다고 말하면 거짓말이다
 * ② 한도 계산          이미 의미가 없는 감시가 3칸 중 한 칸을 잡으면 안 된다
 * ③ 감시 등록 거부      영영 안 울릴 감시를 조용히 받아 두면 안 된다
 * ④ 알림 발송 제외      지난 자리가 풀렸다고 알려 봐야 예약할 수 없다
 * ```
 *
 * ### 왜 함수로 뽑았나 — 실제로 갈라졌기 때문이다 (2026-09-01)
 *
 * 처음엔 넷 다 `date < today` 였다. 그러다 ①② 를 시각까지 보도록 고치면서
 * **③ 을 같이 안 고쳤다.** 그 결과 운영에서 이런 행이 생겼다.
 *
 * ```
 * 10:55:56 에 만든 감시  →  10:20 자리     35분 지난 자리다
 * ```
 *
 * ③ 은 통과시키고 ①② 는 걸러 내니, **저장은 됐는데 목록에 안 보이고 한도에도 안 세는**
 * 행이 남았다. 화면에 id 가 안 나오므로 사용자는 지울 수도 없다.
 *
 * **같은 뜻을 여러 군데 적으면 그중 하나는 반드시 거짓말을 시작한다.**
 * 이 프로젝트에서 문서의 숫자가 계속 그랬고, 이번엔 코드가 그랬다.
 *
 * ### 경계는 "지금" 을 포함한다 (`<=`)
 *
 * 딱 지금 시각인 자리는 **지난 것으로 본다.** JPQL 쪽이 `s.time > :time` 이라
 * 미래를 강한 부등호로 판정하고 있어서, 여기서도 그 반대를 그대로 쓴다.
 * 둘이 어긋나면 경계의 1초 동안 "목록엔 없는데 등록은 되는" 자리가 생긴다.
 *
 * **여유를 두지 않는다.** "10분 뒤 자리는 어차피 못 간다" 같은 판단을 여기 넣고 싶어지는데,
 * 그러면 ①②③④ 가 또 갈라진다. 지켜야 하는 것은 **넷이 똑같이 답하는 것**이지
 * 경계를 잘 잡는 게 아니다. 여유가 필요하면 네 곳 전부에 같은 값으로 넣는다.
 */
fun TimeSlot.isPast(now: LocalDateTime): Boolean = !date.atTime(time).isAfter(now)
